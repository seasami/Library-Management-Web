package Model;

import java.time.LocalDateTime;

public class BorrowingRules {
    private String ruleId;
    private String ruleName;
    private String readerType;
    private Integer maxBooks;
    private Integer loanDays;
    private Integer minAgeForRestrictedBooks;
    private Boolean isActive;
    private String updatedBy;
    private LocalDateTime updatedAt;

    public String getRuleId() {
        return ruleId;
    }

    public void setRuleId(String ruleId) {
        this.ruleId = ruleId;
    }

    public String getRuleName() {
        return ruleName;
    }

    public void setRuleName(String ruleName) {
        this.ruleName = ruleName;
    }

    public String getReaderType() {
        return readerType;
    }

    public void setReaderType(String readerType) {
        this.readerType = readerType;
    }

    public Integer getMaxBooks() {
        return maxBooks;
    }

    public void setMaxBooks(Integer maxBooks) {
        this.maxBooks = maxBooks;
    }

    public Integer getLoanDays() {
        return loanDays;
    }

    public void setLoanDays(Integer loanDays) {
        this.loanDays = loanDays;
    }

    public Integer getMinAgeForRestrictedBooks() {
        return minAgeForRestrictedBooks;
    }

    public void setMinAgeForRestrictedBooks(Integer minAgeForRestrictedBooks) {
        this.minAgeForRestrictedBooks = minAgeForRestrictedBooks;
    }

    public Boolean getIsActive() {
        return isActive;
    }

    public void setIsActive(Boolean isActive) {
        this.isActive = isActive;
    }

    public String getUpdatedBy() {
        return updatedBy;
    }

    public void setUpdatedBy(String updatedBy) {
        this.updatedBy = updatedBy;
    }

    public LocalDateTime getUpdatedAt() {
        return updatedAt;
    }

    public void setUpdatedAt(LocalDateTime updatedAt) {
        this.updatedAt = updatedAt;
    }
}
